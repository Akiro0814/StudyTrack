import { DatabaseSync } from 'node:sqlite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
db.exec(readFileSync(new URL('../StudyTrack/Data/Database/schema.sql',import.meta.url),'utf8'));
const source = readFileSync(new URL('../StudyTrack/Data/Database/SchoolStore.swift',import.meta.url),'utf8');
const schema = source.match(/static let schoolSchema = """\r?\n([\s\S]*?)"""/)[1];
db.exec(schema);
db.exec("INSERT INTO users VALUES('u','甲','甲','2026','2026'),('v','乙','乙','2026','2026')");
db.exec("INSERT INTO semesters VALUES('t','u','高一上','高一上','2026','2026'),('s','u','高一下','高一下','2026','2026')");
const insert = db.prepare('INSERT INTO semester_school VALUES(?,?,?,?,?)');
insert.run('t','u','high',1,1);
assert.throws(()=>insert.run('s','v','high',1,2),'cross-user term metadata');
assert.throws(()=>insert.run('s','u','high',1,1),'duplicate standard term');
assert.throws(()=>insert.run('s','u','high',4,1),'invalid high school year');
assert.throws(()=>insert.run('s','u','custom',1,1),'unsupported stage');
assert.throws(()=>insert.run('s','u','high',1,3),'invalid half');
insert.run('s','u','high',1,2);
db.exec("INSERT INTO subjects VALUES('a','u','t','数学','数学',10000,'2026','2026'),('b','u','s','数学','数学',10000,'2026','2026')");
db.exec("INSERT INTO subject_lineage VALUES('a','shared-math'),('b','shared-math')");
db.exec("DELETE FROM semesters WHERE id='t'");
assert.equal(db.prepare('SELECT COUNT(*) n FROM semester_school').get().n,1);
assert.equal(db.prepare('SELECT COUNT(*) n FROM subject_lineage').get().n,1);
console.log('PASS: school metadata scope, standard-term uniqueness, stage/year/half bounds, cascade');
